const PDFDocument = require('pdfkit');
const TYPES = ['order', 'payment', 'delivery'];
function receiptTypes(o) {
  return ['order', ...(o.payment_status === 'completed' && o.payment_receipt ? ['payment'] : []), ...(o.status === 'delivered' ? ['delivery'] : [])];
}
const fail = (message, status = 400) => Object.assign(new Error(message), { status });
function check(o, type) {
  if (!TYPES.includes(type)) throw fail('Unknown receipt type.');
  if (!receiptTypes(o).includes(type)) throw fail(type === 'payment' ? 'A payment receipt is available only after verified payment.' : 'A delivery receipt is available only after the order is marked delivered.', 409);
}
function renderReceipt(o, s, type, payment) {
  check(o, type);
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A5', margin: 30, info: { Title: `${type} receipt ${o.code}` } });
    const chunks = []; doc.on('data', b => chunks.push(b)); doc.on('end', () => resolve(Buffer.concat(chunks))); doc.on('error', reject);
    const width = doc.page.width - 60;
    const clean = x => String(x ?? '').replace(/[\x00-\x1f]/g, ' ').slice(0, 1200);
    const line = (text, bold = false, size = 10) => {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(size).fillColor('#143D27').text(clean(text), { width }).moveDown(.5);
    };
    const money = v => `${s.currency || 'KSh'} ${Number(v || 0).toLocaleString('en-KE', { minimumFractionDigits: 2 })}`;
    const date = v => v ? new Date(v).toLocaleString('en-KE', { timeZone: 'Africa/Nairobi' }) + ' (Kenya time)' : 'Not recorded';
    line(s.business_name, true, 19); line(`${type.toUpperCase()} RECEIPT`, true, 14);
    line(`Reference: ${o.code}-${type.toUpperCase()}`);
    line(`Order created: ${date(o.created_at)}`);
    line(`Order status: ${o.status}`);
    line(`Payment status: ${o.payment_status === 'completed' ? 'PAID' : 'NOT VERIFIED AS PAID'}`, true);
    if (type === 'payment') {
      line(`M-Pesa receipt: ${o.payment_receipt}`, true);
      line(`Verified: ${date(payment?.updated_at)}`);
      line(`Amount received: ${money(payment?.amount ?? o.total)}`, true);
    }
    if (type === 'delivery') {
      line(`Marked delivered: ${date(o.delivered_at)}`);
      line('Delivery status recorded by the kitchen. This is not a customer signature.');
    }
    line(`Customer: ${o.customer_name}`); line(`Phone: ${o.phone}`); line(`Delivery address: ${o.location}`);
    if (o.delivery_date || o.delivery_time) line(`Scheduled: ${[o.delivery_date, o.delivery_time].filter(Boolean).join(' ')}`);
    line('ITEMS', true, 12);
    let items; try { items = JSON.parse(o.items_json); } catch { items = []; }
    for (const item of items) {
      line(`${item.qty} x ${item.name} — ${money(item.line_total)}`, true);
      for (const option of item.options || []) line(`${option.group}: ${option.choice}`);
      if (item.note) line(item.note);
    }
    line(`Subtotal: ${money(o.subtotal)}`);
    line(`Delivery fee: ${money(o.delivery_fee)}`);
    line(`Order total: ${money(o.total)}`, true, 14);
    if (type !== 'payment') line('This document confirms the order or delivery, not payment.', true);
    line('Generated by the ordering system. Not a tax invoice.');
    doc.end();
  });
}
function routes(app, { requireAdmin, trackedOrder, db, getSettings, wrap }) {
  const send = async (req, res, order) => {
    if (!order) throw fail('Order not found.', 404);
    const type = req.query.type || 'order'; check(order, type);
    const payment = type === 'payment' ? await db.one("SELECT amount,updated_at FROM sunpay_attempts WHERE order_id=$1 AND status='completed' LIMIT 1", [order.id]) : null;
    if (type === 'payment' && !payment) throw fail('Verified payment record not found.', 409);
    const pdf = await renderReceipt(order, getSettings(), type, payment);
    const name = String(order.code).replace(/[^A-Za-z0-9_-]/g, '');
    res.set({ 'Cache-Control': 'no-store', 'Content-Disposition': `attachment; filename="${name}-${type}-receipt.pdf"` }).type('application/pdf').send(pdf);
  };
  app.get('/api/admin/orders/:code/receipt.pdf', requireAdmin, wrap(async (req, res) => send(req, res, await db.one('SELECT * FROM orders WHERE code=$1', [req.params.code]))));
  app.get('/api/track/:token/receipt.pdf', wrap(async (req, res) => send(req, res, await trackedOrder(req.params.token))));
}
module.exports = { receiptTypes, check, renderReceipt, routes };
